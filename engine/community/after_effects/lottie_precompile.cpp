// Build-time tool: compiles lottie_shim.js and every module it reaches to
// QuickJS bytecode, writes them as a C++ array to <out>. The engine reads
// them with JS_ReadObject instead of parsing the sources on every script
// load (community/script_runner/script_runner.cpp).
//
// Canonical module names used throughout:
//   "motolii-lottie-shim"           → the shim itself.
//   "motolii-lottie/<relative>"     → a file under <lottie_root>/<relative>.
// The normalizer that turns './x' and '../x' into these is shared with the
// runtime: community/after_effects/lottie_canonical.h.
//
//   lottie_precompile <lottie_root> <shim_path> <out_cc>
//
// Must run at build time (CMake custom_command). The resulting .cc is
// compiled into motolii_community_after_effects.

#include <quickjs.h>

#include <cctype>
#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

#include "community/after_effects/lottie_canonical.h"

namespace {

struct BuildCtx {
  std::filesystem::path root;
  std::filesystem::path shim;
  std::map<std::string, std::vector<uint8_t>> bytecode;
  std::vector<std::string> order;
};

std::string read_file(const std::filesystem::path& p) {
  std::ifstream f(p, std::ios::binary);
  std::ostringstream s;
  s << f.rdbuf();
  return s.str();
}

// Build-time loader: resolves the canonical name to a file, compiles the
// source with COMPILE_ONLY, serializes the compiled module to bytecode,
// records it, and returns the module def so QuickJS can keep resolving
// further imports.
JSModuleDef* lottie_build_load(JSContext* cx, const char* name, void* opq) {
  auto* b = static_cast<BuildCtx*>(opq);
  const std::string n = name;
  std::filesystem::path path;
  if (n == motolii::kLottieShimCanonical) {
    path = b->shim;
  } else if (n.rfind(motolii::kLottiePrefix, 0) == 0) {
    path = b->root / n.substr(std::string(motolii::kLottiePrefix).size());
  } else {
    std::fprintf(stderr, "lottie_precompile: unknown module name %s\n", name);
    return nullptr;
  }
  const std::string src = read_file(path);
  if (src.empty()) {
    std::fprintf(stderr, "lottie_precompile: missing %s (%s)\n", name,
                 path.string().c_str());
    return nullptr;
  }
  JSValue built = JS_Eval(cx, src.c_str(), src.size(), name,
                          JS_EVAL_TYPE_MODULE | JS_EVAL_FLAG_COMPILE_ONLY);
  if (JS_IsException(built)) {
    JSValue e = JS_GetException(cx);
    const char* msg = JS_ToCString(cx, e);
    std::fprintf(stderr, "lottie_precompile: compile %s failed: %s\n", name,
                 msg ? msg : "?");
    if (msg) JS_FreeCString(cx, msg);
    JS_FreeValue(cx, e);
    return nullptr;
  }
  size_t len = 0;
  uint8_t* bytes =
      JS_WriteObject(cx, &len, built,
                     JS_WRITE_OBJ_BYTECODE | JS_WRITE_OBJ_STRIP_SOURCE |
                         JS_WRITE_OBJ_STRIP_DEBUG);
  if (bytes && len) {
    b->bytecode[n] = std::vector<uint8_t>(bytes, bytes + len);
    b->order.push_back(n);
  }
  if (bytes) js_free(cx, bytes);
  auto* m = static_cast<JSModuleDef*>(JS_VALUE_GET_PTR(built));
  JS_FreeValue(cx, built);
  return m;
}

void write_output(const std::filesystem::path& out, const BuildCtx& b) {
  std::ofstream f(out, std::ios::binary);
  f << "// Generated by lottie_precompile from community/after_effects/"
       "lottie_shim.js\n"
       "// and its transitive imports. Do not edit by hand.\n"
       "#include \"community/after_effects/lottie_bytecode.h\"\n\n"
       "namespace motolii {\n\n";
  for (size_t i = 0; i < b.order.size(); ++i) {
    const auto& data = b.bytecode.at(b.order[i]);
    f << "static const unsigned char kLottieBc_" << i << "[" << data.size()
      << "] = {";
    for (size_t j = 0; j < data.size(); ++j) {
      if (j % 16 == 0) f << "\n  ";
      f << static_cast<int>(data[j]) << ',';
    }
    f << "\n};\n";
  }
  f << "\nconst LottieBytecodeEntry kLottieBytecode[] = {\n";
  for (size_t i = 0; i < b.order.size(); ++i) {
    const auto& name = b.order[i];
    const auto& data = b.bytecode.at(name);
    f << "  {\"" << name << "\", kLottieBc_" << i << ", " << data.size()
      << "},\n";
  }
  f << "};\n"
       "const std::size_t kLottieBytecodeCount = "
    << b.order.size() << ";\n\n"
    << "}  // namespace motolii\n";
}

}  // namespace

int main(int argc, char** argv) {
  if (argc != 4) {
    std::fprintf(
        stderr,
        "usage: lottie_precompile <lottie_root> <shim_path> <out.cc>\n");
    return 1;
  }
  BuildCtx b;
  b.root = argv[1];
  b.shim = argv[2];
  const std::filesystem::path out_cc = argv[3];
  JSRuntime* rt = JS_NewRuntime();
  JSContext* cx = JS_NewContext(rt);
  JS_SetModuleLoaderFunc(rt, motolii::lottie_canonical, lottie_build_load, &b);
  JSModuleDef* m = lottie_build_load(cx, motolii::kLottieShimCanonical, &b);
  if (!m) {
    std::fprintf(stderr, "lottie_precompile: failed at the shim\n");
    JS_FreeContext(cx);
    JS_FreeRuntime(rt);
    return 2;
  }
  write_output(out_cc, b);
  std::fprintf(stderr, "lottie_precompile: wrote %zu modules to %s\n",
               b.order.size(), out_cc.string().c_str());
  JS_FreeContext(cx);
  JS_FreeRuntime(rt);
  return 0;
}
