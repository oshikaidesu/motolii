// Builds the triangles of a flat shape for its current path and appends them to d->sheet.
// The fill comes first, with no triangles if the shape is hollow. It is tessellated by libtess2
// and rebuilt only when `refill` is true or the mesh is empty. The edge follows, generated by
// ThorVG's own stroker with the dash settings of d->fx and the trim range [trimFrom, trimTo].
// A vertex has a uv in units of the shape's height, measured from its center, and a pos that is
// the same offset scaled to stage units. Returns the index where each part ends: the fill, then
// the edge if there is one. A part without triangles gets one empty triangle.
std::vector<uint32_t> shape_cut(Canvas2D* d, float trimFrom, float trimTo, bool refill) {
    const tvg::PathCommand* cmds; const tvg::Point* pts; uint32_t cmdsCnt = 0, ptsCnt = 0;
    d->outline->path(&cmds, &cmdsCnt, &pts, &ptsCnt);
    Mesh& m = *d->sheet;
    const float w = d->cutW, h = d->plainHigh;
    // Appends a vertex for the path point (x, y), given in a w-by-h space with y pointing down.
    const auto point = [&](float x, float y) {
        const float2 at{(x - 0.5f * w) / h, (0.5f * h - y) / h};
        m.pos.push_back({d->sheetHigh * at, 0.f}), m.nrm.push_back({0, 0, 1}), m.uv.push_back(at);
    };
    // Gives an otherwise empty part one empty triangle.
    const auto none = [&] { if (m.pos.empty()) point(0.5f * w, 0.5f * h); for (int k = 0; k < 3; ++k) m.idx.push_back(0); };
    if (refill || m.idx.empty()) {
        m.pos.clear(), m.nrm.clear(), m.uv.clear(), m.idx.clear();
        // Voxelized path: it is made of squares, each already two triangles, so nothing needs
        // cutting.
        if (!d->hollow && d->bent[9] > 0.f) {
            for (uint32_t c = 0, p = 0; c < cmdsCnt; ++c)
                if (cmds[c] == tvg::PathCommand::MoveTo && c + 3 < cmdsCnt) {
                    const uint32_t k = (uint32_t)m.pos.size();
                    for (uint32_t i = 0; i < 4; ++i) point(pts[p + i].x, pts[p + i].y);
                    m.idx.insert(m.idx.end(), {k, k + 1, k + 2, k, k + 2, k + 3});
                    p += 4, c += 3;
                }
        } else if (!d->hollow) {
            // Tessellate the outline. Curves are already split into short pieces, so each curve is
            // represented by its end point.
            TESStesselator* t = tessNewTess(nullptr);
            std::vector<float2> ring;
            const auto end = [&] { if (ring.size() > 2) tessAddContour(t, 2, ring.data(), sizeof(float2), (int)ring.size()); ring.clear(); };
            // The path left after trimming, closed with a straight line. It is filled
            // instead of the full path when a trim is set.
            std::vector<tvg::PathCommand> partBy;
            std::vector<tvg::Point> partAt;
            const bool part = trimFrom > 0.f || trimTo < 1.f;
            if (part) sk_trim(cmds, cmdsCnt, pts, trimFrom, trimTo, partBy, partAt);
            const tvg::PathCommand* fillBy = part ? partBy.data() : cmds;
            const tvg::Point* fillAt = part ? partAt.data() : pts;
            const uint32_t fillCnt = part ? (uint32_t)partBy.size() : cmdsCnt;
            for (uint32_t c = 0, p = 0; c < fillCnt; ++c) switch (fillBy[c]) {
                case tvg::PathCommand::MoveTo: end(); ring.push_back({fillAt[p].x, fillAt[p].y}); ++p; break;
                case tvg::PathCommand::LineTo: ring.push_back({fillAt[p].x, fillAt[p].y}); ++p; break;
                case tvg::PathCommand::CubicTo: ring.push_back({fillAt[p + 2].x, fillAt[p + 2].y}); p += 3; break;
                case tvg::PathCommand::Close: end(); break;
            }
            end();
            if (tessTesselate(t, d->fx.evenOdd ? TESS_WINDING_ODD : TESS_WINDING_NONZERO, TESS_POLYGONS, 3, 2, nullptr)) {
                const TESSreal* v = tessGetVertices(t);
                for (int i = 0; i < tessGetVertexCount(t); ++i) point(v[2 * i], v[2 * i + 1]);
                const TESSindex* e = tessGetElements(t);
                for (int i = 0; i < 3 * tessGetElementCount(t); ++i) m.idx.push_back((uint32_t)e[i]);
            }
            tessDeleteTess(t);
        }
        if (m.idx.empty()) none();
        d->fillPoints = (uint32_t)m.pos.size(), d->fillEnd = (uint32_t)m.idx.size();
    } else {
        // Keep the fill built earlier and rebuild only the edge.
        m.pos.resize(d->fillPoints), m.nrm.resize(d->fillPoints), m.uv.resize(d->fillPoints), m.idx.resize(d->fillEnd);
    }
    if (d->edgeWide <= 0.f) return {d->fillEnd};
    std::vector<float> xy;
    std::vector<uint32_t> idx;
    // A negative cap or join selects ThorVG's defaults: a square cap and a bevel join.
    tvg_edge(cmds, cmdsCnt, pts, ptsCnt, d->edgeWide, d->fx.cap < 0 ? (int)tvg::StrokeCap::Square : d->fx.cap, d->fx.join < 0 ? (int)tvg::StrokeJoin::Bevel : d->fx.join,
             d->fx.dash * h, d->fx.dashFrom * h, trimFrom, trimTo, xy, idx);
    const uint32_t base = (uint32_t)m.pos.size();
    for (size_t i = 0; i < xy.size(); i += 2) point(xy[i], xy[i + 1]);
    for (uint32_t i : idx) m.idx.push_back(base + i);
    // Arrowheads on open outlines: at the end, at the start, or both, wherever the trim leaves
    // them. Each is a shape in the edge's color pointing the way the line goes.
    if (d->fx.heads) {
        // Names of the Alight Motion line ends, indexed by shape - 5.
        static const char* const alight[] = {"t-line", "square", "square-filled", "diamond", "diamond-filled", "arrow-hollow", "arrow-filled", "circle-hollow", "circle-filled", "teardrop-hollow", "teardrop-filled"};
        // Appends one arrowhead of the given shape to the mesh. `at` is the end of the line and
        // `back` is a point behind it that gives the line's direction.
        const auto head = [&](tvg::Point at, tvg::Point back, int shape) {
            float dx = at.x - back.x, dy = at.y - back.y;
            const float len = std::hypot(dx, dy), l = d->fx.headSize * d->edgeWide;
            if (len < 1e-4f) return;
            dx /= len, dy /= len;
            if (shape >= 5) {
                // Shapes 5 and up are Alight Motion's line ends, drawn as in absent_ends.cpp
                // and as long as ours. The outline is tessellated by libtess2 like the
                // fill, with each curve split into 8 pieces.
                std::vector<tvg::PathCommand> c;
                std::vector<tvg::Point> p;
                if (!sk_svg(absent_line_end(at.x, at.y, dx, dy, 0.5f * l, d->edgeWide, d->fx.cap, d->fx.join, alight[std::min(shape - 5, 10)]).c_str(), c, p)) return;
                TESStesselator* t = tessNewTess(nullptr);
                std::vector<float2> ring;
                const auto close = [&] { if (ring.size() > 2) tessAddContour(t, 2, ring.data(), sizeof(float2), (int)ring.size()); ring.clear(); };
                for (size_t i = 0, q = 0; i < c.size(); ++i) switch (c[i]) {
                    case tvg::PathCommand::MoveTo: close(); ring.push_back({p[q].x, p[q].y}); ++q; break;
                    case tvg::PathCommand::LineTo: ring.push_back({p[q].x, p[q].y}); ++q; break;
                    case tvg::PathCommand::CubicTo: {
                        const float2 a = ring.empty() ? float2{p[q].x, p[q].y} : ring.back(), b{p[q].x, p[q].y}, e{p[q + 1].x, p[q + 1].y}, f{p[q + 2].x, p[q + 2].y};
                        for (int k = 1; k <= 8; ++k) { const float u = (float)k / 8.f, v = 1.f - u; ring.push_back(v * v * v * a + 3.f * v * v * u * b + 3.f * v * u * u * e + u * u * u * f); }
                        q += 3;
                        break;
                    }
                    case tvg::PathCommand::Close: close(); break;
                }
                close();
                if (tessTesselate(t, TESS_WINDING_NONZERO, TESS_POLYGONS, 3, 2, nullptr)) {
                    const uint32_t k = (uint32_t)m.pos.size();
                    const TESSreal* v = tessGetVertices(t);
                    for (int i = 0; i < tessGetVertexCount(t); ++i) point(v[2 * i], v[2 * i + 1]);
                    const TESSindex* e = tessGetElements(t);
                    for (int i = 0; i < 3 * tessGetElementCount(t); ++i) m.idx.push_back(k + (uint32_t)e[i]);
                }
                tessDeleteTess(t);
                return;
            }
            const uint32_t k = (uint32_t)m.pos.size();
            // Adds a vertex at the offsets `along` and `across` in the head's own frame:
            // along the direction of the line and across it, in units of the head length `l`.
            const auto put = [&](float along, float across) { point(at.x + along * l * dx - across * l * dy, at.y + along * l * dy + across * l * dx); };
            const auto quad = [&](uint32_t a) { m.idx.insert(m.idx.end(), {a, a + 1, a + 2, a, a + 2, a + 3}); };
            switch (shape) {
                case 1: {
                    // A circle at the end, like Cavalry's circleHead.
                    put(0.f, 0.f);
                    for (int i = 0; i <= 24; ++i) put(0.4f * std::cos(TAU * (float)i / 24.f), 0.4f * std::sin(TAU * (float)i / 24.f));
                    for (uint32_t i = 0; i < 24; ++i) m.idx.insert(m.idx.end(), {k, k + 1 + i, k + 2 + i});
                    break;
                }
                // A square, like Cavalry's boxHead.
                case 2: put(0.35f, -0.35f), put(0.35f, 0.35f), put(-0.35f, 0.35f), put(-0.35f, -0.35f), quad(k); break;
                case 3: {
                    // An open V as thick as the edge, like Cavalry's chevronHead.
                    const float w = 0.5f * d->edgeWide / l;
                    put(0.5f, w), put(0.5f, -w), put(-0.4f, -0.45f - w), put(-0.4f, -0.45f + w), quad(k);
                    put(0.5f, -w), put(0.5f, w), put(-0.4f, 0.45f + w), put(-0.4f, 0.45f - w), quad(k + 4);
                    break;
                }
                // A bar across the end.
                case 4: put(0.f + 0.5f * d->edgeWide / l, -0.45f), put(0.f + 0.5f * d->edgeWide / l, 0.45f), put(-0.5f * d->edgeWide / l, 0.45f), put(-0.5f * d->edgeWide / l, -0.45f), quad(k); break;
                // A triangle, like Cavalry's basicArrowHead.
                default: put(0.5f, 0.f), put(-0.5f, 0.4f), put(-0.5f, -0.4f), m.idx.insert(m.idx.end(), {k, k + 1, k + 2});
            }
        };
        std::vector<float> ends;
        for (int k = 0, n = sk_ends(cmds, cmdsCnt, pts, trimFrom, trimTo, ends); k < n; ++k) {
            const float* e = &ends[8 * (size_t)k];
            if (d->fx.heads & 1) head({e[0], e[1]}, {e[0] - e[2], e[1] - e[3]}, d->fx.headShape);
            if (d->fx.heads & 2) head({e[4], e[5]}, {e[4] - e[6], e[5] - e[7]}, d->fx.headStart >= 0 ? d->fx.headStart : d->fx.headShape);
        }
    }
    if (idx.empty()) none();
    return {d->fillEnd, (uint32_t)m.idx.size()};
}

// Bytes held by all cached cuts, and the limit of 256 MiB.
std::atomic<size_t> cuts_held{0};
constexpr size_t cuts_most = 256ull << 20;
// Returns a hash of every input a cut depends on.
uint64_t cut_key(float3 trim, const std::array<float, 10>& bend, const Canvas2D::Other& join, const Canvas2D::Other& morph, const Canvas2D::Other& trace) {
    // FNV-1a over everything the cut depends on.
    uint64_t h = 1469598103934665603ull;
    const auto mix = [&](const void* p, size_t n) { for (size_t i = 0; i < n; ++i) h = (h ^ ((const uint8_t*)p)[i]) * 1099511628211ull; };
    mix(&trim, sizeof trim), mix(bend.data(), sizeof bend);
    for (const Canvas2D::Other* o : {&join, &morph, &trace})
        mix(&o->how, sizeof o->how), mix(&o->much, sizeof o->much), mix(o->by.data(), o->by.size() * sizeof(tvg::PathCommand)), mix(o->at.data(), o->at.size() * sizeof(tvg::Point));
    return h;
}

