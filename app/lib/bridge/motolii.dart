// The app's side of the engine's C API (engine/motolii.h), called directly through dart:ffi.
//
// The app holds no document of its own. It holds this handle and the numbers of the layers.
// Each call is one change and one undo step. A call that fails returns false, and [error] says why.
// macOS and Debug builds only: the Debug entitlements turn the sandbox off so the library can be loaded.
import 'dart:async';
import 'dart:convert';
import 'dart:ffi';
import 'dart:io';
import 'dart:isolate';

import 'package:ffi/ffi.dart';

import 'package:motolii/bridge/engine_paths.dart' show motoliiDir;
import 'package:motolii/bridge/motolii_bindings.dart' as c; // The engine's calls as generated by ffigen (see ffigen.yaml).

typedef EngineHandle = Pointer<c.Motolii>;

/// Runs one engine call on another isolate. No project data is passed over.
///
/// [words] are the string arguments; they are freed once [call] has returned.
Future<T> askEngine<T>(String lib, List<String> words, T Function(c.MotoliiBindings, List<Pointer<Utf8>>) call) =>
    Isolate.run(() => using((a) => call(c.MotoliiBindings(DynamicLibrary.open(lib)), [for (final w in words) w.toNativeUtf8(allocator: a)])));

/// What a media file is, as the engine's GStreamer discoverer reports it: size, frame rate and duration for a video,
/// and its kind. Empty when the file cannot be read. Runs on another isolate.
final _mediaInfos = <String, Future<List<String>>>{};
Future<List<String>> _mediaSaid(String lib, String file) =>
    _mediaInfos[file] ??= askEngine(lib, [file], (b, w) => b.motolii_media_info(w[0]).toDartString().split(' '));

/// How long a media file plays, in seconds. 0 for an image or an unreadable file.
Future<double> mediaSecondsOf(String lib, String file) async => switch (await _mediaSaid(lib, file)) {
  final s when s.length >= 5 => double.parse(s[3]),
  _ => 0,
};

/// Reads a project's properties without opening it, on another isolate: size, duration and frame rate as last saved
/// (see Motolii.poster). Its preview image is written to [png]. Null if the project saved none or is not a project.
Future<({int wide, int high, double seconds, double rate})?> docFactsOf(String lib, String doc, String png) => askEngine(lib, [doc, png], (b, w) {
  final said = b.motolii_doc_properties(w[0], w[1]).toDartString().split(' ');
  return said.length < 4 ? null : (wide: int.parse(said[0]), high: int.parse(said[1]), seconds: double.parse(said[2]), rate: double.parse(said[3]));
});

Future<String> mediaInfoOf(String lib, String file) async {
  final said = await _mediaSaid(lib, file);
  if (said.length < 5) return '';
  final rate = double.parse(said[2]), seconds = double.parse(said[3]);
  return [
    if (said[0] != '0') '${said[0]} × ${said[1]}',
    if (rate > 0) '${rate == rate.roundToDouble() ? rate.round() : rate.toStringAsFixed(2)} fps',
    if (seconds > 0) '${seconds.toStringAsFixed(1)} s',
    said.skip(4).join(' '),
  ].where((s) => s.isNotEmpty).join(' · ');
}

/// Finds where a video fails the IRIS photosensitivity check (motolii_flashes, on another isolate).
///
/// Results are cached in ~/Library/Caches/Motolii/flashes. Each stretch is (from, to) in seconds. A frame fails on
/// more than three flashes in a second, two to three flashes for five seconds, or a pattern (see the tool's README;
/// frameData.json lists the frames that do not pass). Empty means the video passes. Null means it could not be read.
Future<List<(double, double)>?> flashesOf(String lib, String video) async {
  final folder = '${Platform.environment['HOME']}/Library/Caches/Motolii/flashes';
  final written = await askEngine(lib, [video, folder], (b, w) => b.motolii_flashes(w[0], w[1]).toDartString());
  if (written.isEmpty) return null;
  try {
    final frames = (jsonDecode(File('${File(written).parent.path}/frameData.json').readAsStringSync()) as Map)['NonPassFrameData'] as Map;
    List<num> of(String k) => [...(frames[k] as List? ?? const []).cast<num>()];
    final n = of('Frame'), luminance = of('LuminanceFrameResult'), red = of('RedFrameResult'), pattern = of('PatternFrameResult');
    final at = [
      for (final s in (frames['TimeStampString'] as List? ?? const []).cast<String>()) s.split(':').fold<double>(0, (a, p) => a * 60 + double.parse(p)),
    ];
    final fails = <(double, double)>[];
    for (var i = 0; i < n.length; i++) {
      if (luminance[i] < 2 && red[i] < 2 && pattern[i] < 1) continue;
      if (fails.isNotEmpty && i > 0 && n[i - 1] == n[i] - 1 && fails.last.$2 == at[i - 1]) {
        // The previous frame failed too, so this extends the same stretch.
        fails.last = (fails.last.$1, at[i]);
      } else {
        fails.add((at[i], at[i]));
      }
    }
    return fails;
  } catch (_) {
    return null;
  }
}

class Motolii {
  Motolii._(this._lib, this.handle, this.libPath, this.home);
  final DynamicLibrary _lib;
  // The engine's calls, generated by ffigen from motolii.h (see ffigen.yaml).
  late final bindings = c.MotoliiBindings(_lib);
  final EngineHandle handle;
  final String libPath;

  /// The folder that relative file names in the project are resolved against.
  final String home;

  /// Opens the project at [document], creating it if missing, with a stage of [wide] by [high]. Null if it cannot be opened.
  static Motolii? open(String document, {int wide = 1920, int high = 1080, String? dir}) {
    dir ??= motoliiDir;
    final path = '$dir/out/libmotolii.dylib';
    final DynamicLibrary lib;
    try {
      lib = DynamicLibrary.open(path);
    } catch (_) {
      return null;
    }
    final home = '$dir/out/filament_webgpu'.toNativeUtf8(), doc = document.toNativeUtf8();
    c.MotoliiBindings(lib).motolii_home(home);
    final m = c.MotoliiBindings(lib).motolii_open(doc, wide, high);
    malloc
      ..free(home)
      ..free(doc);
    if (m == nullptr) return null;
    return Motolii._(lib, m, path, '$dir/out/filament_webgpu').._listen();
  }

  // ---- snapshots (docs/app/BRIDGE.md)
  // The app reads the project only through two snapshots made by the engine's render thread.
  // The project snapshot is rebuilt whenever the project changes. The time snapshot is rebuilt with each frame.
  // The engine reports which one is new through a single listener. Nothing here queries the project directly,
  // and nothing waits for the render thread.
  late final _snapshot = bindings.motolii_snapshot;
  late final _addListener = bindings.motolii_add_listener;
  NativeCallable<Void Function(Int)>? _listenerCallable;
  // The project-wide part of the project snapshot.
  Map<String, dynamic> documentSnapshot = const {};
  // Each layer's part of the project snapshot, as of the version it arrived with.
  final layerSnapshots = <int, Map<String, dynamic>>{};
  Map<String, dynamic> momentSnapshot = const {'layer': {}};
  int _documentAt = -1, _momentAt = -1;

  /// Called when a snapshot is new. [document] is the project snapshot, [moment] the time snapshot,
  /// and [cache] means the frames cached on disk changed.
  void Function({required bool document, required bool moment, required bool cache})? listener;

  // The engine's property tables per layer kind. They are the same for every project, so they are read once.
  final kindProperties = <String, Set<String>>{};
  static List<double> numbers(Object? said) => [for (final n in (said as List<dynamic>?) ?? const []) (n as num).toDouble()];

  /// The cards the user added through More, per layer. They live only while the app is open and are not saved in the project.
  final asked = <int, Set<String>>{};

  late final _close = bindings.motolii_close;

  Set<int> watched = const {};

  int? deskId;

  final unaskedSaid = <String>{};

  late final _shaping = bindings.motolii_shaping;

  /// The names of the properties that change which cards a layer has, and its name. The engine owns this rule; it is asked once.
  late final Set<String> shaping = _shaping(handle).toDartString().split(' ').toSet();

  // Shelf items by name and by file.
  final shelfItems = <String, ShelfItem>{};
  // Shelf items by listing: screen, layer, preset, motion, relation.
  final shelfListings = <String, List<ShelfItem>>{};

  // How each property is displayed, read from the layers' parts once per project snapshot.
  final shownOf = <String, Shown?>{};

  /// What the shelf folders hold (create scripts, effects, animators). It is not part of the project, and is read once and again after [forgetFolders].
  final folders = <String, List<(String, String)>>{};

  /// Makes the next request read the folders again.
  ///
  /// Call it when a file in a watched folder is added, removed or overwritten (see workspace/effect_tiles.dart).
  /// The engine also re-reads its files (motolii_files_changed), and only now.
  void forgetFolders() {
    bindings.motolii_files_changed();
    folders.clear();
    shelfItems.clear();
    shelfListings.clear();
  }

  final fontKinds = <String, Set<String>>{};

  late final _answer = bindings.motolii_answer;
  late final _answerWhy = bindings.motolii_answer_why;

  final waiting = <int, Completer<(int, String)>>{};

  /// The ids of all layers.
  List<int> get layers => [for (final t in (documentSnapshot['layers'] as List<dynamic>?) ?? const []) t as int];

  String get answerWhy => _answerWhy(handle).toDartString();

  /// Resolves a file name from the project to a full path.
  String whole(String file) => Uri.directory(home).resolveUri(Uri.file(file)).toFilePath();

  void _listen() {
    _listenerCallable = NativeCallable<Void Function(Int)>.listener(takeSnapshots);
    _addListener(handle, _listenerCallable!.nativeFunction);
    takeSnapshots(7);
  }

  void takeSnapshots(int which) {
    // An answer arrived, so both snapshots are read. A step's end is heard late and comes with what the step made, as answer() does.
    if (which & 8 != 0) which |= 3;
    final version = malloc<Long>();
    if (which & 1 != 0) {
      final p = _snapshot(handle, 1, _documentAt, version), all = jsonDecode(p.toDartString()) as Map<String, dynamic>;
      malloc.free(p);
      // Same version as before: not new, so nothing is reported.
      if (version.value == _documentAt) which &= ~1;
      _documentAt = version.value;
      if (all['document'] case final Map<String, dynamic> d) documentSnapshot = d;
      (all['layer'] as Map<String, dynamic>).forEach((t, part) => layerSnapshots[int.parse(t)] = part as Map<String, dynamic>);
      final are = {0, ...layers};
      layerSnapshots.removeWhere((t, _) => !are.contains(t));
      shownOf.clear();
    }
    if (which & 2 != 0) {
      final p = _snapshot(handle, 2, 0, version);
      if (version.value == _momentAt) {
        // Same version as before: not new.
        which &= ~2;
      } else {
        momentSnapshot = jsonDecode(p.toDartString()) as Map<String, dynamic>;
        _momentAt = version.value;
      }
      malloc.free(p);
    }
    malloc.free(version);
    if (which & 8 != 0) {
      // An answer is ready: check each change that was waiting.
      for (final t in [...waiting.keys]) {
        final a = _answer(handle, t);
        if (a >= 0) waiting.remove(t)!.complete((a, a >= 1 ? '' : answerWhy));
      }
    }
    if (which & 7 != 0) listener?.call(document: which & 1 != 0, moment: which & 2 != 0, cache: which & 4 != 0);
  }

  /// Reads both snapshots right away, as the engine made them before it answered a change the app waited for.
  T tookSnapshots<T>(T answer) {
    takeSnapshots(3);
    return answer;
  }

  T withStrings<T>(List<String> words, T Function(List<Pointer<Utf8>>) call) =>
      // package:ffi's Arena frees every string when the call returns.
      using((a) => call([for (final w in words) w.toNativeUtf8(allocator: a)]));

  void close() {
    _addListener(handle, nullptr);
    _listenerCallable?.close();
    _close(handle);
  }
}

/// How a property is shown to the user (see Motolii.shown): its widget style, unit, label, slider range and fold.
class Shown {
  const Shown(this.look, this.unit, this.label, this.low, this.high, this.fold, {this.open = false});
  final String look, unit, label;
  final double low, high;

  /// The fold it sits in on its card, named by what the fold holds. Null means the card's first row.
  final String? fold;

  /// Whether the user may type values outside [low] and [high], which only set the slider's range (see the engine's document/edit/layer_edit.h).
  final bool open;
}

/// One item on a shelf, parsed from the engine's tab-separated line "name\tfile\tlabel\tpicture\thome\tsame\tabout\ttags".
/// [from] is the listing it came from: screen, layer, preset, motion or relation.
class ShelfItem {
  ShelfItem(this.id, this.name, {this.label = '', this.picture = '', this.home = '', this.same = false, this.about = '', this.tags = const {}, this.from = ''});
  final String id, name, label, home, about, from;
  final Set<String> tags;
  String picture;
  bool same;
}
