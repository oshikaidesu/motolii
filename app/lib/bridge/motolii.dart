typedef EngineHandle = Pointer<c.Motolii>;

/// Runs one engine call on another isolate.
Future<T> askEngine<T>(
  String lib,
  List<String> words,
  T Function(c.MotoliiBindings, List<Pointer<Utf8>>) call,
) => Isolate.run(
  () => using(
    (a) => call(c.MotoliiBindings(DynamicLibrary.open(lib)), [
      for (final w in words) w.toNativeUtf8(allocator: a),
    ]),
  ),
);

// Media info cache (GStreamer discoverer, on another isolate).
final _mediaInfos = <String, Future<List<String>>>{};
Future<List<String>> _mediaSaid(String lib, String file) =>
    _mediaInfos[file] ??= askEngine(lib, [
      file,
    ], (b, w) => b.motolii_media_info(w[0]).toDartString().split(' '));

/// Duration in seconds. 0 for images or unreadable files.
Future<double> mediaSecondsOf(String lib, String file) async =>
    switch (await _mediaSaid(lib, file)) {
      final s when s.length >= 5 => double.parse(s[3]),
      _ => 0,
    };

/// Reads a project's properties without opening it. Writes its preview to [png].
Future<({int wide, int high, double seconds, double rate})?> docFactsOf(
  String lib,
  String doc,
  String png,
) => askEngine(lib, [doc, png], (b, w) {
  final said = b.motolii_doc_properties(w[0], w[1]).toDartString().split(' ');
  return said.length < 4
      ? null
      : (
          wide: int.parse(said[0]),
          high: int.parse(said[1]),
          seconds: double.parse(said[2]),
          rate: double.parse(said[3]),
        );
});

Future<String> mediaInfoOf(String lib, String file) async {
  final said = await _mediaSaid(lib, file);
  if (said.length < 5) return '';
  final rate = double.parse(said[2]), seconds = double.parse(said[3]);
  return [
    if (said[0] != '0') '${said[0]} × ${said[1]}',
    if (rate > 0)
      '${rate == rate.roundToDouble() ? rate.round() : rate.toStringAsFixed(2)} fps',
    if (seconds > 0) '${seconds.toStringAsFixed(1)} s',
    said.skip(4).join(' '),
  ].where((s) => s.isNotEmpty).join(' · ');
}

/// IRIS photosensitivity check (motolii_flashes, another isolate).
/// Returns failing stretches as (from, to) in seconds. Empty = passes. Null = unreadable.
Future<List<(double, double)>?> flashesOf(String lib, String video) async {
  final folder =
      '${Platform.environment['HOME']}/Library/Caches/Motolii/flashes';
  final written = await askEngine(lib, [
    video,
    folder,
  ], (b, w) => b.motolii_flashes(w[0], w[1]).toDartString());
  if (written.isEmpty) return null;
  try {
    final frames =
        (jsonDecode(
              File('${File(written).parent.path}/frameData.json')
                  .readAsStringSync(),
            ) as Map)['NonPassFrameData']
            as Map;
    List<num> of(String k) => [...(frames[k] as List? ?? const []).cast<num>()];
    final n = of('Frame'),
        luminance = of('LuminanceFrameResult'),
        red = of('RedFrameResult'),
        pattern = of('PatternFrameResult');
    final at = [
      for (final s
          in (frames['TimeStampString'] as List? ?? const []).cast<String>())
        s.split(':').fold<double>(0, (a, p) => a * 60 + double.parse(p)),
    ];
    final fails = <(double, double)>[];
    for (var i = 0; i < n.length; i++) {
      if (luminance[i] < 2 && red[i] < 2 && pattern[i] < 1) continue;
      if (fails.isNotEmpty &&
          i > 0 &&
          n[i - 1] == n[i] - 1 &&
          fails.last.$2 == at[i - 1]) {
        // The previous frame failed too, so this extends the same stretch.
        fails.last = (fails.last.$1, at[i]);
      } else {
        fails.add((at[i], at[i]));
      }
    }
    return fails;
  } catch (e, stack) {
    log(
      'flashesOf: failed to parse IRIS result for $video: $e',
      name: 'motolii',
      error: e,
      stackTrace: stack,
    );
    return null;
  }
}

class Motolii {
  Motolii._(this._lib, this.handle, this.libPath, this.home);
  final DynamicLibrary _lib;
  // Generated by ffigen (see ffigen.yaml).
  late final bindings = c.MotoliiBindings(_lib);
  final EngineHandle handle;
  final String libPath;

  final String home;

  /// Opens the project at [document], creating it if missing. Null if it cannot be opened.
  static Motolii? open(
    String document, {
    int wide = 1920,
    int high = 1080,
    String? dir,
  }) {
    dir ??= motoliiDir;
    final path = _liveCopy('$dir/out/libmotolii.dylib');
    final DynamicLibrary lib;
    try {
      lib = DynamicLibrary.open(path);
    } catch (e, stack) {
      log(
        'engine library failed to open at $path: $e',
        name: 'motolii',
        error: e,
        stackTrace: stack,
      );
      return null;
    }
    final home = '$dir/out/filament_webgpu'.toNativeUtf8(),
        doc = document.toNativeUtf8();
    c.MotoliiBindings(lib).motolii_home(home);
    final m = c.MotoliiBindings(lib).motolii_open(doc, wide, high);
    malloc
      ..free(home)
      ..free(doc);
    if (m == nullptr) return null;
    return Motolii._(lib, m, path, '$dir/out/filament_webgpu').._listen();
  }

  /// A copy named after its build time so dyld loads the new engine on hot restart.
  static String _liveCopy(String built) {
    final from = File(built);
    if (!from.existsSync()) return built;
    final live = Directory('${from.parent.path}/live')
      ..createSync(recursive: true);
    final copy =
        '${live.path}/libmotolii-${from.lastModifiedSync().microsecondsSinceEpoch}.dylib';
    if (File(copy).existsSync()) return copy;
    for (final old in live.listSync()) {
      try {
        old.deleteSync();
      } on FileSystemException catch (_) {
        // Expected: an older engine build still has this file mapped. dyld keeps it; we move on.
      }
    }
    from.copySync('$copy.part');
    File('$copy.part').renameSync(copy);
    return copy;
  }

  // ---- snapshots (docs/app/BRIDGE.md)
  late final _snapshot = bindings.motolii_snapshot;
  late final _addListener = bindings.motolii_add_listener;
  // ReceivePort, not NativeCallable: on hot restart a stale engine posts to a
  // closed port (safe); a freed NativeCallable would crash.
  final _told = ReceivePort();
  Map<String, dynamic> documentSnapshot = const {};
  final layerSnapshots = <int, Map<String, dynamic>>{};
  Map<String, dynamic> momentSnapshot = const {'layer': {}};
  // Binary: [now, count, ids..., 26-doubles-per-layer...]. NaN = absent.
  static const _timeLayoutCap = 2 + 1024 + 1024 * 26;
  late final bool _hasTimeLayout = _lib.providesSymbol('motolii_time_layout');
  Pointer<Double>? _timeBuf;
  Float64List timeLayout = Float64List(0);
  Map<int, int> timeIndex = const {};
  int _documentAt = -1, _momentAt = -1;

  /// Called when a snapshot is new.
  void Function({
    required bool document,
    required bool moment,
    required bool cache,
  })?
  listener;

  // Read once; same for every project.
  final kindProperties = <String, Set<String>>{};
  static List<double> numbers(Object? said) => [
    for (final n in (said as List<dynamic>?) ?? const []) (n as num).toDouble(),
  ];

  /// Cards the user added via More. Not saved in the project.
  final asked = <int, Set<String>>{};

  late final _close = bindings.motolii_close;

  Set<int> watched = const {};

  int? deskId;

  final unaskedSaid = <String>{};

  late final _shaping = bindings.motolii_shaping;

  /// Properties that change which cards a layer has. Asked once.
  late final Set<String> shaping = _shaping(handle)
      .toDartString()
      .split(' ')
      .toSet();

  final shelfItems = <String, ShelfItem>{};
  final shelfListings = <String, List<ShelfItem>>{};

  // Display info per property, rebuilt each project snapshot.
  final shownOf = <String, Shown?>{};

  /// Shelf folder contents. Re-read after [forgetFolders].
  final folders = <String, List<(String, String)>>{};

  /// Invalidates the cached folders so the next request re-reads them.
  void forgetFolders() {
    bindings.motolii_files_changed();
    folders.clear();
    shelfItems.clear();
    shelfListings.clear();
  }

  final fontKinds = <String, Set<String>>{};

  late final _answer = bindings.motolii_answer;
  late final _answerWhy = bindings.motolii_answer_why;

  final waiting = <int, Completer<(int, String)>>{};

  List<int> get layers => [
    for (final t in (documentSnapshot['layers'] as List<dynamic>?) ?? const [])
      t as int,
  ];

  String get answerWhy => _answerWhy(handle).toDartString();

  /// Resolves a relative project path to absolute.
  String whole(String file) =>
      Uri.directory(home).resolveUri(Uri.file(file)).toFilePath();

  void _listen() {
    _told.listen((which) {
      if (which is int) {
        takeSnapshots(
          which,
        ); // (a null: the engine asking whether anyone is listening)
      }
    });
    _addListener(
      handle,
      NativeApi.postCObject.cast(),
      _told.sendPort.nativePort,
    );
    takeSnapshots(7);
  }

  void takeSnapshots(int which) {
    // An answer arrived: read both snapshots.
    if (which & 8 != 0) which |= 3;
    final version = malloc<Long>();
    if (which & 1 != 0) {
      final p = _snapshot(handle, 1, _documentAt, version);
      final Map<String, dynamic> all;
      try {
        all = jsonDecode(p.toDartString()) as Map<String, dynamic>;
      } catch (e, stack) {
        malloc.free(p);
        malloc.free(version);
        log(
          'document snapshot: JSON parse failed: $e',
          name: 'motolii',
          error: e,
          stackTrace: stack,
        );
        return;
      }
      malloc.free(p);
      // Same version: skip.
      if (version.value == _documentAt) which &= ~1;
      _documentAt = version.value;
      if (all['document'] case final Map<String, dynamic> d) {
        documentSnapshot = d;
      }
      (all['layer'] as Map<String, dynamic>).forEach(
        (t, part) =>
            layerSnapshots[int.parse(t)] = part as Map<String, dynamic>,
      );
      final are = {0, ...layers};
      layerSnapshots.removeWhere((t, _) => !are.contains(t));
      shownOf.clear();
    }
    if (which & 2 != 0) {
      if (_hasTimeLayout) {
        _timeBuf ??= malloc<Double>(_timeLayoutCap);
        final layoutSize = bindings.motolii_time_layout(
          handle,
          _timeBuf!,
          _timeLayoutCap,
        );
        if (layoutSize >= 2) {
          timeLayout = _timeBuf!.asTypedList(layoutSize);
          final n = timeLayout[1].toInt();
          final base = 2 + n;
          timeIndex = {
            for (var i = 0; i < n; i++)
              timeLayout[2 + i].toInt(): base + i * 26,
          };
        }
      }
      final p = _snapshot(handle, 2, 0, version);
      if (version.value == _momentAt) {
        which &= ~2;
      } else {
        try {
          momentSnapshot = jsonDecode(p.toDartString()) as Map<String, dynamic>;
        } catch (e, stack) {
          log(
            'moment snapshot: JSON parse failed: $e',
            name: 'motolii',
            error: e,
            stackTrace: stack,
          );
        }
        _momentAt = version.value;
      }
      malloc.free(p);
    }
    malloc.free(version);
    if (which & 8 != 0) {
      for (final t in [...waiting.keys]) {
        final a = _answer(handle, t);
        if (a >= 0) waiting.remove(t)!.complete((a, answerWhy));
      }
    }
    if (which & 7 != 0) {
      listener?.call(
        document: which & 1 != 0,
        moment: which & 2 != 0,
        cache: which & 4 != 0,
      );
    }
  }

  /// Reads both snapshots immediately (the engine made them before it answered).
  T tookSnapshots<T>(T answer) {
    takeSnapshots(3);
    return answer;
  }

  T withStrings<T>(List<String> words, T Function(List<Pointer<Utf8>>) call) =>
      using((a) => call([for (final w in words) w.toNativeUtf8(allocator: a)]));

  void close() {
    _addListener(handle, nullptr, 0);
    _told.close();
    _close(handle);
  }
}

/// Display metadata for a property.
class Shown {
  const Shown(
    this.look,
    this.unit,
    this.label,
    this.low,
    this.high,
    this.fold, {
    this.open = false,
  });
  final String look, unit, label;
  final double low, high;

  /// Fold name on its card. Null = first row.
  final String? fold;

  /// Whether [low]/[high] are soft limits (slider range only).
  final bool open;
}

/// One item on a shelf. [from]: the listing (screen, layer, preset, motion, relation).
class ShelfItem {
  ShelfItem(
    this.id,
    this.name, {
    this.label = '',
    this.picture = '',
    this.home = '',
    this.same = false,
    this.about = '',
    this.tags = const {},
    this.from = '',
  });
  final String id, name, label, home, about, from;
  final Set<String> tags;
  String picture;
  bool same;
}
